/**
 * Points the apps at the platform's address. Run before `cap sync`:
 *
 *   APP_SITE_URL=https://example.com node scripts/set-site.mjs
 *
 * Writes www/site.js, which the bundled pages (offline screen, library) and
 * capacitor.config.ts read. CI passes the repository variable
 * PRODUCTION_SITE_URL, so moving the platform to a new domain needs no code
 * change: update the variable and rebuild the apps. Without APP_SITE_URL the
 * current address is kept.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'www', 'site.js');
const current = /APP_SITE_URL = '([^']+)'/.exec(readFileSync(file, 'utf8'))?.[1];
const requested = (process.env.APP_SITE_URL || current || '').trim();

let url;
try {
  url = new URL(requested);
} catch {
  console.error(`Not a valid address: "${requested}"`);
  process.exit(1);
}
if (url.protocol !== 'https:') {
  console.error('The apps only load the platform over https.');
  process.exit(1);
}

const site = `${url.origin}/`;
writeFileSync(
  file,
  `// Generated by scripts/set-site.mjs: the platform address the apps open.\nwindow.APP_SITE_URL = '${site}';\n`,
);
console.log(`Apps will open ${site}`);
